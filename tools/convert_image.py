#!/usr/bin/env python3
"""Convert a PNG/JPEG image to RGB565 raw bytes for loading into FT800 RAM_G.

Usage:
  python3 convert_image.py input.png output.bin
  python3 convert_image.py input.png output.h --header

The output binary can be loaded via CMD_LOADIMAGE (for JPEG/PNG) or directly
written to RAM_G as a raw RGB565 bitmap.  For CMD_LOADIMAGE the raw binary is
fed as a data stream; the co-processor handles JPEG decompression internally.

For raw RGB565 output:
  - Each pixel = 2 bytes, little-endian
  - Size = width * height * 2
  - FT800 RAM_G limit = 256 kB total

Requires: Pillow  (pip install Pillow)
"""

import argparse
import struct
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    print("ERROR: Pillow not installed.  Run: pip install Pillow", file=sys.stderr)
    sys.exit(1)


def to_rgb565(img: Image.Image) -> bytes:
    """Convert a PIL image to RGB565 little-endian bytes."""
    img = img.convert("RGB")
    result = bytearray()
    for r, g, b in img.getdata():
        # Pack: R[7:3] | G[7:2] | B[7:3]
        pixel = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        result += struct.pack("<H", pixel)
    return bytes(result)


def to_c_header(data: bytes, varname: str, width: int, height: int) -> str:
    """Emit a C/C++ header with the bitmap as a PROGMEM array."""
    lines = [
        f"// Auto-generated by tools/convert_image.py",
        f"// Size: {width}x{height} pixels, {len(data)} bytes (RGB565)",
        f"#pragma once",
        f"#include <pgmspace.h>",
        f"static constexpr uint16_t {varname}_WIDTH  = {width};",
        f"static constexpr uint16_t {varname}_HEIGHT = {height};",
        f"static const uint8_t {varname}_DATA[] PROGMEM = {{",
    ]
    row = []
    for i, byte in enumerate(data):
        row.append(f"0x{byte:02X}")
        if len(row) == 16:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ", ".join(row))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Convert image to FT800 RGB565")
    parser.add_argument("input",  help="Input image (PNG, JPEG, BMP, etc.)")
    parser.add_argument("output", help="Output file (.bin or .h)")
    parser.add_argument("--header", action="store_true",
                        help="Output as C/C++ PROGMEM header")
    parser.add_argument("--max-size", type=int, default=256 * 1024,
                        help="Warn if output exceeds this many bytes (default: 256kB = FT800 RAM_G)")
    args = parser.parse_args()

    img = Image.open(args.input)
    w, h = img.size
    print(f"Input:  {args.input}  ({w}×{h} pixels)")

    data = to_rgb565(img)
    print(f"Output: {len(data)} bytes RGB565")

    if len(data) > args.max_size:
        print(f"WARNING: Output ({len(data)} B) exceeds FT800 RAM_G ({args.max_size} B).", file=sys.stderr)

    out_path = Path(args.output)
    varname = out_path.stem.upper().replace("-", "_").replace(" ", "_")

    if args.header:
        out_path.write_text(to_c_header(data, varname, w, h))
        print(f"Written: {out_path}  (C header with PROGMEM array '{varname}_DATA')")
    else:
        out_path.write_bytes(data)
        print(f"Written: {out_path}")


if __name__ == "__main__":
    main()
